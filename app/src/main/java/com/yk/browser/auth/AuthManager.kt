package com.yk.browser.auth

import android.content.Context
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider

/**
 * Browser account: Firebase Authentication via Google Sign-In.
 * The Firebase uid scopes the user's cloud vault in Firestore.
 *
 * Firebase is optional at build time: without app/google-services.json the
 * app still compiles and runs, but account/cloud features report
 * "not configured" until the file is added (see FIREBASE_SETUP.md).
 */
object AuthManager {

    /** False when app/google-services.json hasn't been added yet. */
    fun isFirebaseConfigured(context: Context): Boolean =
        FirebaseApp.getApps(context).isNotEmpty()

    fun isSignedIn(): Boolean = try {
        FirebaseAuth.getInstance().currentUser != null
    } catch (e: IllegalStateException) {
        false // Firebase not configured
    }

    fun currentEmail(): String? = try {
        FirebaseAuth.getInstance().currentUser?.email
    } catch (e: IllegalStateException) {
        null
    }

    fun googleSignInOptions(context: Context): GoogleSignInOptions {
        val builder = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestEmail()
        // default_web_client_id is generated by the google-services plugin;
        // absent when google-services.json hasn't been added yet.
        webClientId(context)?.let { builder.requestIdToken(it) }
        return builder.build()
    }

    fun signInWithGoogle(idToken: String) =
        FirebaseAuth.getInstance().signInWithCredential(
            GoogleAuthProvider.getCredential(idToken, null)
        )

    fun signOut(context: Context) {
        try {
            FirebaseAuth.getInstance().signOut()
        } catch (e: IllegalStateException) {
            // Firebase not configured — nothing to sign out from
        }
        GoogleSignIn.getClient(context, googleSignInOptions(context)).signOut()
    }

    private fun webClientId(context: Context): String? {
        val resId = context.resources.getIdentifier(
            "default_web_client_id", "string", context.packageName
        )
        return if (resId != 0) context.getString(resId) else null
    }
}
